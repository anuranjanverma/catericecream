<?php
/**
 * Submission coordination table ({prefix}cic_submissions). Holds no personal data:
 * - Atomic retry claim: the UNIQUE key_hash means only one request per submission key can store
 *   an enquiry (INSERT IGNORE decides the winner inside MySQL, so concurrent retries cannot both win).
 * - The Flamingo message id the claim produced (workflow references the Flamingo record).
 * - Per-channel notification state, claimed with conditional UPDATEs so a notification is sent
 *   at most once even when a retry, a scheduled job and an admin "Retry" overlap.
 * - A random receipt and a non-personal summary (event, location, treat labels) for the
 *   confirmation page, so refreshing it shows the same confirmation without re-submitting.
 *
 * @package CIC
 */

namespace CIC\Enquiries;

defined( 'ABSPATH' ) || exit;

final class Store {

	/** Confirmation receipts are readable for this long. */
	public const RECEIPT_TTL = DAY_IN_SECONDS;

	public static function table(): string {
		global $wpdb;
		return $wpdb->prefix . 'cic_submissions';
	}

	public static function ready(): bool {
		return (int) get_option( \CIC\Config::OPTION_SCHEMA_VERSION, 0 ) >= 5;
	}

	public static function hash( string $key ): string {
		return hash_hmac( 'sha256', $key, wp_salt( 'nonce' ) );
	}

	/** Submission keys are 16–64 URL-safe characters generated by the form. */
	public static function valid_key( string $key ): bool {
		return (bool) preg_match( '/^[A-Za-z0-9_-]{16,64}$/', $key );
	}

	/**
	 * Claim a submission key. Returns 'claimed' for the first request, otherwise the existing row's
	 * state: 'stored' (already saved: replay its receipt) or 'processing' (another request is
	 * saving it right now).
	 *
	 * @return array{state: string, row: array<string, mixed>|null}
	 */
	public static function claim( string $form, string $key ): array {
		global $wpdb;
		$now      = current_time( 'mysql', true );
		$inserted = $wpdb->query( $wpdb->prepare( 'INSERT IGNORE INTO ' . self::table() . ' (form, key_hash, status, summary, created_at, updated_at) VALUES (%s, %s, %s, %s, %s, %s)', $form, self::hash( $key ), 'processing', '', $now, $now ) ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared
		$row      = self::by_key( $key );
		if ( 1 === (int) $inserted ) {
			return array( 'state' => 'claimed', 'row' => $row );
		}
		return array( 'state' => $row ? (string) $row['status'] : 'processing', 'row' => $row );
	}

	/** @return array<string, mixed>|null */
	public static function by_key( string $key ): ?array {
		global $wpdb;
		$row = $wpdb->get_row( $wpdb->prepare( 'SELECT * FROM ' . self::table() . ' WHERE key_hash = %s', self::hash( $key ) ), ARRAY_A ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared
		return $row ?: null;
	}

	/** @return array<string, mixed>|null */
	public static function by_flamingo( int $flamingo_id ): ?array {
		global $wpdb;
		$row = $wpdb->get_row( $wpdb->prepare( 'SELECT * FROM ' . self::table() . ' WHERE flamingo_id = %d', $flamingo_id ), ARRAY_A ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared
		return $row ?: null;
	}

	/**
	 * Confirmation summary for a receipt (null when unknown or expired).
	 *
	 * @return array<string, mixed>|null
	 */
	public static function receipt( string $receipt ): ?array {
		global $wpdb;
		if ( ! preg_match( '/^[a-f0-9]{32}$/', $receipt ) ) {
			return null;
		}
		$row = $wpdb->get_row( $wpdb->prepare( 'SELECT form, summary, created_at FROM ' . self::table() . " WHERE receipt = %s AND status = 'stored'", $receipt ), ARRAY_A ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared
		if ( ! $row || strtotime( $row['created_at'] . ' UTC' ) < time() - self::RECEIPT_TTL ) {
			return null;
		}
		$summary         = json_decode( (string) $row['summary'], true );
		$summary         = is_array( $summary ) ? $summary : array();
		$summary['form'] = (string) $row['form'];
		return $summary;
	}

	/**
	 * Mark a claim as stored with its Flamingo message and receipt summary.
	 *
	 * @param array<string, mixed> $summary Non-personal labels only.
	 */
	public static function complete( string $key, int $flamingo_id, array $summary ): string {
		global $wpdb;
		$receipt = bin2hex( random_bytes( 16 ) );
		$wpdb->update(
			self::table(),
			array(
				'status'      => 'stored',
				'flamingo_id' => $flamingo_id,
				'receipt'     => $receipt,
				'summary'     => wp_json_encode( $summary ),
				'updated_at'  => current_time( 'mysql', true ),
			),
			array( 'key_hash' => self::hash( $key ) )
		);
		return $receipt;
	}

	/** Storage failed: free the key so the visitor can retry the same submission. */
	public static function release( string $key ): void {
		global $wpdb;
		$wpdb->delete( self::table(), array( 'key_hash' => self::hash( $key ), 'status' => 'processing' ) );
	}

	/**
	 * Claim one notification channel for sending ('operator' or 'customer'). Only a channel that is
	 * pending or failed can be claimed; the UPDATE is atomic, so overlapping attempts cannot both win.
	 */
	public static function claim_channel( int $flamingo_id, string $channel ): bool {
		global $wpdb;
		if ( ! in_array( $channel, array( 'operator', 'customer' ), true ) ) {
			return false;
		}
		$col = $channel . '_status';
		return 1 === (int) $wpdb->query( $wpdb->prepare( 'UPDATE ' . self::table() . " SET {$col} = 'sending', attempts = attempts + 1, updated_at = %s WHERE flamingo_id = %d AND {$col} IN ('pending', 'failed')", current_time( 'mysql', true ), $flamingo_id ) ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared,WordPress.DB.PreparedSQL.InterpolatedNotPrepared -- column from allowlist.
	}

	/** Record a channel outcome: sent, failed or skipped (with a non-personal error code). */
	public static function set_channel( int $flamingo_id, string $channel, string $status, string $error = '' ): void {
		global $wpdb;
		if ( ! in_array( $channel, array( 'operator', 'customer' ), true ) || ! in_array( $status, array( 'pending', 'sent', 'failed', 'skipped' ), true ) ) {
			return;
		}
		$wpdb->update(
			self::table(),
			array(
				$channel . '_status' => $status,
				'last_error'         => mb_substr( sanitize_key( $error ), 0, 100 ),
				'updated_at'         => current_time( 'mysql', true ),
			),
			array( 'flamingo_id' => $flamingo_id )
		);
	}

	/**
	 * Enquiries whose notifications still need delivery (for the retry job and the admin screen).
	 *
	 * @return array<int, array<string, mixed>>
	 */
	public static function undelivered( int $limit = 20 ): array {
		global $wpdb;
		return $wpdb->get_results( $wpdb->prepare( 'SELECT * FROM ' . self::table() . " WHERE status = 'stored' AND (operator_status IN ('pending','failed') OR customer_status IN ('pending','failed')) ORDER BY id LIMIT %d", $limit ), ARRAY_A ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared
	}

	/** Release channels stuck in "sending" (a crashed request) so they can be retried. */
	public static function unstick( int $minutes = 15 ): void {
		global $wpdb;
		$before = gmdate( 'Y-m-d H:i:s', time() - $minutes * MINUTE_IN_SECONDS );
		foreach ( array( 'operator_status', 'customer_status' ) as $col ) {
			$wpdb->query( $wpdb->prepare( 'UPDATE ' . self::table() . " SET {$col} = 'failed', last_error = 'interrupted' WHERE {$col} = 'sending' AND updated_at < %s", $before ) ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared,WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		}
	}

	/** Remove abandoned claims and old rows whose enquiry is gone (retention). */
	public static function cleanup(): void {
		global $wpdb;
		$t = self::table();
		$wpdb->query( $wpdb->prepare( "DELETE FROM {$t} WHERE status = 'processing' AND created_at < %s", gmdate( 'Y-m-d H:i:s', time() - HOUR_IN_SECONDS ) ) ); // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$wpdb->query( "DELETE s FROM {$t} s LEFT JOIN {$wpdb->posts} p ON p.ID = s.flamingo_id WHERE s.status = 'stored' AND p.ID IS NULL" ); // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared,WordPress.DB.DirectDatabaseQuery
	}
}
