<?php
/**
 * cic_event custom post type (BUILD_SPECIFICATION §8). Lives in the core plugin so event content
 * survives a theme change. Public archive /events/, REST editing, revisions, own capabilities.
 *
 * @package CIC
 */

namespace CIC\Content;

defined( 'ABSPATH' ) || exit;

final class EventType {

	public const POST_TYPE = 'cic_event';

	public function register(): void {
		add_action( 'init', array( $this, 'register_post_type' ) );
	}

	public function register_post_type(): void {
		register_post_type(
			self::POST_TYPE,
			array(
				'labels'          => array(
					'name'               => __( 'Events', 'cater-ice-cream-core' ),
					'singular_name'      => __( 'Event', 'cater-ice-cream-core' ),
					'add_new_item'       => __( 'Add new event', 'cater-ice-cream-core' ),
					'edit_item'          => __( 'Edit event', 'cater-ice-cream-core' ),
					'new_item'           => __( 'New event', 'cater-ice-cream-core' ),
					'view_item'          => __( 'View event', 'cater-ice-cream-core' ),
					'search_items'       => __( 'Search events', 'cater-ice-cream-core' ),
					'not_found'          => __( 'No events found', 'cater-ice-cream-core' ),
					'all_items'          => __( 'All events', 'cater-ice-cream-core' ),
					'archives'           => __( 'Events', 'cater-ice-cream-core' ),
					'menu_name'          => __( 'Events', 'cater-ice-cream-core' ),
				),
				'description'     => __( 'Occasions Cater Ice Cream caters, such as birthdays and weddings. Not dated inventory or availability.', 'cater-ice-cream-core' ),
				'public'          => true,
				'show_in_rest'    => true,
				'rest_base'       => 'events',
				'has_archive'     => 'events',
				'rewrite'         => array(
					'slug'       => 'events',
					'with_front' => false,
				),
				'hierarchical'    => false,
				'menu_position'   => 26,
				'menu_icon'       => 'dashicons-heart',
				'supports'        => array( 'title', 'editor', 'excerpt', 'thumbnail', 'revisions', 'page-attributes', 'custom-fields' ),
				'capability_type' => array( 'cic_event', 'cic_events' ),
				'map_meta_cap'    => true,
				'template'        => array(),
			)
		);
	}

	/**
	 * Primitive capabilities generated by capability_type cic_event / cic_events.
	 *
	 * @return string[]
	 */
	public static function capabilities(): array {
		return array(
			'edit_cic_events',
			'edit_others_cic_events',
			'edit_private_cic_events',
			'edit_published_cic_events',
			'publish_cic_events',
			'read_private_cic_events',
			'delete_cic_events',
			'delete_others_cic_events',
			'delete_private_cic_events',
			'delete_published_cic_events',
		);
	}

	/** Administrators and editors manage events. Run by the v2 migration; idempotent. */
	public static function grant_capabilities(): void {
		foreach ( array( 'administrator', 'editor' ) as $role_name ) {
			$role = get_role( $role_name );
			if ( ! $role ) {
				continue;
			}
			foreach ( self::capabilities() as $cap ) {
				$role->add_cap( $cap );
			}
		}
	}
}
